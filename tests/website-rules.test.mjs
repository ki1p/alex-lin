import assert from 'node:assert/strict';
import {kindOf,fieldValue,chooseForm,receiptOutcome} from '../website-rules.mjs';
const field=(label,type='text')=>({label,type,name:'',id:'',placeholder:''});
assert.equal(kindOf(field('First Name')),'first_name');
assert.equal(kindOf(field('Confirm Email')),'email');
assert.equal(kindOf(field('Country')),'country');
assert.equal(kindOf(field('Sign up for newsletter','checkbox')),'unsupported');
assert.equal(kindOf(field('Password','password')),'restricted');
assert.equal(fieldValue(field('Zip code'),{},'Body','Subject'),'');
assert.equal(fieldValue(field('Machine Type','radio'),{},'Body','Subject'),'');
assert.equal(fieldValue(field('Address'),{city:'Cangzhou',province:'Hebei',country:'China'},'',''),'Cangzhou, Hebei, China');
const newsletter={text:'Subscribe newsletter',fields:[field('Email','email')]};
const contact={text:'Contact us',fields:[field('Name'),field('Email','email'),field('Message','textarea')]};
assert.equal(chooseForm([newsletter,contact]),contact);
assert.equal(chooseForm([newsletter]),undefined);
assert.equal(fieldValue({...field('Category'),options:[{text:'Water & Waste Water products'}]}, {},'We supply PE pipes',''),'Water & Waste Water products');
assert.equal(fieldValue(field('Phone'),{phone:'+86 17731796591'},'',''),'+8617731796591');
assert.equal(fieldValue(field('Phone'),{phone:'0086 (177) 3179-6591'},'',''),'+8617731796591');
assert.equal(receiptOutcome({dialogs:[{type:'alert',message:'phone must contain a number'}]}).status,'needs_attention');
assert.equal(receiptOutcome({validationResult:false}).status,'needs_attention');
assert.equal(receiptOutcome({dialogs:[{type:'alert',message:'Message sent successfully'}]}).status,'submitted');
assert.equal(receiptOutcome({before:'Thank you for your message',text:'Thank you for your message'}).status,'uncertain');
assert.equal(receiptOutcome({requests:[{kind:'response',status:500}]}).status,'uncertain');
assert.equal(receiptOutcome({requests:[{kind:'response',status:200}]}).status,'uncertain');
console.log('website-rules: 19 assertions passed');
